import fs from 'node:fs';
import vm from 'node:vm';
import assert from 'node:assert/strict';
import ts from 'typescript';
const source=fs.readFileSync(new URL('../lib/player-home.ts',import.meta.url),'utf8');
const {outputText}=ts.transpileModule(source,{compilerOptions:{module:ts.ModuleKind.CommonJS,target:ts.ScriptTarget.ES2022}});
const exports={};vm.runInNewContext(outputText,{exports});
const game=(id,extra={})=>({id,status:'OPEN',attendance_status:'INVITED',game_date:'2099-01-01',start_time:'20:00',live:false,format:5,going:0,...extra});
const early=game('a'),declined=game('b',{game_date:'2098-01-01',attendance_status:'DECLINED'}),live=game('c',{live:true,game_date:'2099-02-01'});
assert.equal(exports.nextPlayerGame([declined,early]).id,'a');
assert.equal(exports.nextPlayerGame([declined]).id,'b');
assert.equal(exports.nextPlayerGame([early,live]).id,'c');
assert.equal(exports.nextPlayerGame([game('closed',{status:'CLOSED'})]),undefined);
assert.equal(exports.nextPlayerGame([]),undefined);
assert.equal(exports.nextPlayerGame([game('unknown',{start_time:null}),early]).id,'a');
const original=[live,early];exports.nextPlayerGame(original);assert.deepEqual(original,[live,early]);
assert.equal(exports.playersNeeded(game('5')),10);
assert.equal(exports.playersNeeded(game('7',{format:7,going:11})),3);
assert.equal(exports.playersNeeded(game('full',{going:20})),0);
console.log('PASS player home: eligible next game, live priority, declined fallback, unknown time, immutable input and minimum two-team count');
