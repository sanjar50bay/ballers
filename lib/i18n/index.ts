import catalog from "./catalog.json";
export type Locale = "ru" | "kk";
const messages: Record<string, { ru: string; kk: string }> = { ...catalog };
for (const value of Object.values(catalog)) messages[value.kk] ??= value;
let locale: Locale = "ru";
const listeners = new Set<() => void>();
export const languageKey = "ballers:locale";
export const getLocale = () => locale;
export const serverLocale = (): Locale => "ru";
export function subscribeLocale(listener: () => void) {
  listeners.add(listener);
  return () => {
    listeners.delete(listener);
  };
}
export function setLocale(value: Locale) {
  locale = value;
  if (typeof window !== "undefined") {
    try {
      localStorage.setItem(languageKey, value);
    } catch {}
    document.documentElement.lang = value;
  }
  listeners.forEach((fn) => fn());
}
export function t(
  source: string,
  values?: Record<string, string | number>,
): string {
  let text = messages[source.trim()]?.[locale] ?? source;
  if (values)
    for (const [key, value] of Object.entries(values))
      text = text.replaceAll(`{${key}}`, String(value));
  return text;
}
export function dateLocale() {
  return getLocale() === "kk" ? "kk-KZ" : "ru-RU";
}
export function uiError(source?: string | null) {
  if (source && messages[source.trim()]) return t(source);
  // Do not expose SQL, RLS or English network internals as interface text.
  return t("Действие не выполнено. Проверь соединение и повтори попытку.");
}
export function positionLabel(code: string | null | undefined) {
  return t(
    (
      {
        GK: "Вратарь",
        DEF: "Защитник",
        MID: "Полузащитник",
        ATT: "Нападающий",
      } as Record<string, string>
    )[code ?? ""] ?? "Игрок",
  );
}
export function roleLabel(code: string) {
  return t(
    (
      {
        OWNER: "организатор",
        MANAGER: "менеджер",
        MEMBER: "участник",
        GUEST: "Гости",
      } as Record<string, string>
    )[code] ?? "участник",
  );
}
// Notifications are generated by SQL. Only known system templates are translated;
// captured game/community titles remain untouched.
export function notificationText(message: string) {
  const attendance = message.match(
    /^Ответ на приглашение изменён ответственным: (.+)$/,
  );
  if (attendance)
    return (
      t("Ответ на приглашение изменён ответственным:") +
      " " +
      t(
        (
          {
            GOING: "Иду",
            MAYBE: "Возможно",
            DECLINED: "Не иду",
            INVITED: "Приглашён",
            ожидание: "Ожидание",
          } as Record<string, string>
        )[attendance[1]] || "Ожидание",
      )
    );
  if (getLocale() === "ru") return message;
  const patterns: [RegExp, string][] = [
    [/^Подтвердите результат матча #(.+)$/, "Матч нәтижесін растаңыз №$1"],
    [/^Приглашение: (.+)$/, "Шақыру: $1"],
    [/^Вам предложено место: (.+)$/, "Саған орын ұсынылды: $1"],
  ];
  for (const [pattern, replacement] of patterns)
    if (pattern.test(message)) return message.replace(pattern, replacement);
  return t(message);
}
